def ce(emoji_id: str, fallback: str = "✨") -> str:
    """یه <tg-emoji> تگ HTML آماده برمی‌گردونه. فقط با parse_mode="HTML" کار می‌کنه.

    fallback همون ایموجی معمولی‌ایه که برای کلاینت‌های قدیمی/بدون پشتیبانی
    Custom Emoji نمایش داده می‌شه؛ همیشه یه fallback واقعی و مرتبط بده.
    """
    return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'


def ce_first(category: str, fallback: str = "✨") -> str:
    """اولین ID دسته‌ی داده‌شده رو به‌عنوان تگ <tg-emoji> برمی‌گردونه.
    اگه دسته وجود نداشت، فقط fallback خام (بدون تگ) برمی‌گرده."""
    ids = CUSTOM_EMOJIS.get(category) or []
    if not ids:
        return fallback
    return ce(ids[0], fallback)


def esc(text) -> str:
    """کمکی برای escape کردن متن دینامیک قبل از قرار دادن تو پیام HTML
    (وقتی پیام هم شامل ce() هست و parse_mode="HTML" شده)."""
    return html.escape(str(text), quote=False)
