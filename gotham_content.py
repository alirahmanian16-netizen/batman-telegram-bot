def pick_event_name(main_chance: float = 0.65) -> str:
    """با احتمال بیشتر یکی از رویدادهای اصلی، وگرنه هر رویداد دیگه‌ای رو انتخاب می‌کنه."""
    if random.random() < main_chance:
        idx = random.choice(MAIN_EVENT_INDICES)
    else:
        idx = random.randrange(len(EVENT_NAMES))
    return EVENT_NAMES[idx]


def pick_dialogue_line() -> str:
    """با احتمال کم، یه دیالوگ بونوس (روز هفته/آب‌وهوا/ساعت شب)، وگرنه یکی از ۶۰ دیالوگ اصلی."""
    if random.random() < 0.25 and ALL_BONUS_LINES:
        return random.choice(ALL_BONUS_LINES)
    return random.choice(NIGHT_LINES)


